// JavaScript Variables

// 1. var:
// Old way to declare a variable.
// Can be redeclared and reassigned.

var city = "Coimbatore";
console.log(city);      // Output: Coimbatore

city = "Chennai";
console.log(city);      // Output: Chennai



// 2.let:
// Modern way to declare a variable.
// Cannot be redeclared.
// Can be reassigned.

let age = 20;
console.log(age);       // Output: 20

age = 21;
console.log(age);       // Output: 21



// 3.const:
// Used to declare a constant variable.
// Cannot be redeclared.
// Cannot be reassigned.

const pi = 3.14;
console.log(pi);        // Output: 3.14

const name = "Kalai";
console.log(name);      // Output: Kalai