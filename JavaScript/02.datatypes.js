// JavaScript Data Types

// Data Types:
// Data types define the type of value stored in a variable.

// 1.String:
// Used to store text values.

const myName = "Kalaiselvi";
console.log(myName);           // Output: Kalaiselvi
console.log(typeof myName);    // Output: string


// 2.Number:
// Used to store integer or decimal values.

const age = 45;
console.log(age);              // Output: 45
console.log(typeof age);       // Output: number


// 3.Boolean:
// Used to store true or false values.

const isStudent = true;
console.log(isStudent);        // Output: true
console.log(typeof isStudent); // Output: boolean


// 4.Undefined:
// A variable that is declared but not assigned a value.

let address;
console.log(address);          // Output: undefined
console.log(typeof address);   // Output: undefined