//Condition if/else Statement

//Age check

const Age = 22;
if(Age >= 18){
    console.log("Adult");
}
else{
    console.log("Minor");
}

//Grade check

const mark = 85;
if(mark >= 90){
    console.log("A grade");
}
else if(mark >= 75){
    console.log("B grade")
}
else if(mark >= 60){
    console.log("C grade")
}
else{
    console.log("fail")
}

//Temperature Check

let temp= 60;
if(temp > 35){
    console.log("Hot");
}
else if(temp>=20 && temp<=35){
    console.log("Normal");
}

else{
    console.log("Cold");
}

